#!/usr/bin/env python3
"""Generate the app's sample data from the design prototype's data.

Reads docs/design/prototype/data.js (built from the Fixture Library by the melody lab, #47) and
writes ios/Pedos/Sample/SampleData.generated.swift: the prototype's Songs with their distinct
pitches and their notes, each Fixture Library Recording's analysis, and the story order
simulated recordings follow. The Recording data is Debug-only; the Songs stand in for the Song
Catalog until #38.

The prototype's notes are the melody lab's render of each catalog score, moved into the
Recordings' range. They're moved back into the score's key here, and checked against the
Song's distinct pitches, so the notes and the pitches can't disagree. Debug builds also get
which Fixture Library Recording the render used for each pitch (`r` in data.js), so the sample
model can show the render's own Recordings while it plays that render.

Run from anywhere:
    ios/scripts/generate-sample-data.py           # rewrite the Swift file
    ios/scripts/generate-sample-data.py --check   # fail if the Swift file is out of date
"""
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SOURCE = REPO / "docs/design/prototype/data.js"
AUDIO = REPO / "docs/design/prototype/audio"
OUTPUT = REPO / "ios/Pedos/Sample/SampleData.generated.swift"


def swift_string(text):
    return json.dumps(text, ensure_ascii=False)


def swift_double(value):
    return repr(float(value))


def score_notes(song):
    """The Song's notes in the score's key: the render moved every note by the same interval."""
    rendered = sorted({n["m"] for n in song["notes"]})
    shifts = {m - p for m, p in zip(rendered, song["pitches"])}
    if len(rendered) != len(song["pitches"]) or len(shifts) != 1:
        sys.exit(f"error: Song {song['id']} notes don't match its pitches {song['pitches']}")
    shift = shifts.pop()
    notes = [(n["s"], n["d"], n["m"] - shift) for n in song["notes"]]
    if notes != sorted(notes, key=lambda n: n[0]) or any(d <= 0 for _, d, _ in notes):
        sys.exit(f"error: Song {song['id']} notes aren't in time order with positive lengths")
    return notes


def render_shift(song):
    """How many semitones the render moved the Song's notes."""
    return min(n["m"] for n in song["notes"]) - song["pitches"][0]


def render_fixtures(song):
    """The Fixture Library Recording the render used for each of the Song's pitches (score key)."""
    shift = render_shift(song)
    fixtures = {}
    for n in song["notes"]:
        pitch = n["m"] - shift
        if fixtures.setdefault(pitch, n["r"]) != n["r"]:
            sys.exit(f"error: Song {song['id']} render plays pitch {pitch} with more than one Recording")
    if len(set(fixtures.values())) != len(fixtures):
        sys.exit(f"error: Song {song['id']} render plays two pitches with one Recording")
    return fixtures


def load():
    text = SOURCE.read_text(encoding="utf-8").strip()
    prefix = "window.PROTO = "
    if not text.startswith(prefix) or not text.endswith(";"):
        sys.exit(f"error: {SOURCE} doesn't look like the prototype's data.js")
    return json.loads(text[len(prefix):-1])


def render(data):
    recordings, songs, story = data["recordings"], data["songs"], data["story"]
    ids = {r["id"] for r in recordings}
    for r in recordings:
        if r["melodic"] != (r["midi"] is not None):
            sys.exit(f"error: Recording {r['id']} is melodic={r['melodic']} with midi={r['midi']}")
        if not (AUDIO / f"rec-{r['id']}.mp3").is_file():
            sys.exit(f"error: no audio for Recording {r['id']} in {AUDIO}")
    for fixture_id in story:
        if fixture_id not in ids:
            sys.exit(f"error: story names unknown Recording {fixture_id}")
    melodic = {r["id"] for r in recordings if r["melodic"]}
    for s in songs:
        if not set(render_fixtures(s).values()) <= melodic:
            sys.exit(f"error: Song {s['id']} render uses a Recording that isn't Melodic")
        if s["pitches"] != sorted(set(s["pitches"])):
            sys.exit(f"error: Song {s['id']} pitches aren't distinct and sorted")
        if not (AUDIO / f"song-{s['id']}.mp3").is_file():
            sys.exit(f"error: no audio for Song {s['id']} in {AUDIO}")

    lines = [
        "// Generated by ios/scripts/generate-sample-data.py from docs/design/prototype/data.js.",
        "// Do not edit by hand: rerun the script instead.",
        "",
        "extension Song {",
        "    /// The design prototype's Songs (#47), with each Song's distinct pitches as MIDI note",
        "    /// numbers and its notes (start and length in beats). They stand in for the Song Catalog",
        "    /// until #38 bundles it.",
        "    static let prototypeCatalog: [Song] = [",
    ]
    for s in songs:
        lines += [
            "        Song(",
            f"            id: {swift_string(s['id'])}, title: {swift_string(s['title'])}, "
            f"pitches: {json.dumps(s['pitches'])},",
            f"            source: {swift_string(s['source'])}, bpm: {s['bpm']},",
            "            notes: [",
        ]
        notes = [
            f"Note(start: {swift_double(start)}, length: {swift_double(length)}, pitch: {pitch})"
            for start, length, pitch in score_notes(s)
        ]
        for i in range(0, len(notes), 3):
            lines.append("                " + ", ".join(notes[i:i + 3]) + ",")
        lines += [
            "            ]",
            "        ),",
        ]
    lines += [
        "    ]",
        "}",
        "",
        "#if INTERNAL",
        "extension SampleFixture {",
        "    /// Every Fixture Library Recording, with the reference analysis the prototype used.",
        "    static let prototypeLibrary: [SampleFixture] = [",
    ]
    for r in recordings:
        pitch = "nil" if r["midi"] is None else swift_double(r["midi"])
        lines.append(
            f"        SampleFixture(id: {swift_string(r['id'])}, pitch: {pitch}, "
            f"seconds: {swift_double(r['seconds'])}, firstFartUsed: {'true' if r['cut'] else 'false'}),"
        )
    lines += [
        "    ]",
        "",
        "    /// The order simulated recordings arrive in: a noise-like one first, then pitches that",
        "    /// unlock Songs step by step.",
        f"    static let prototypeStory: [String] = [{', '.join(swift_string(i) for i in story)}]",
        "}",
        "",
        "extension Song {",
        "    /// How the design prototype rendered each Song (`song-<id>.mp3`): its transposition,",
        "    /// and the Fixture Library Recording that plays each pitch, by pitch in the score's key.",
        "    static let prototypeRenders: [Song.ID: StandInRender] = [",
    ]
    for s in songs:
        fixtures = render_fixtures(s)
        pairs = ", ".join(f"{pitch}: {swift_string(fixtures[pitch])}" for pitch in sorted(fixtures))
        lines.append(
            f"        {swift_string(s['id'])}: StandInRender(transposition: {render_shift(s)}, fixtureForPitch: [{pairs}]),"
        )
    lines += [
        "    ]",
        "}",
        "#endif",
        "",
    ]
    return "\n".join(lines)


def main():
    swift = render(load())
    if "--check" in sys.argv[1:]:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != swift:
            sys.exit(f"error: {OUTPUT.relative_to(REPO)} is out of date; run ios/scripts/generate-sample-data.py")
        print(f"ok    {OUTPUT.relative_to(REPO)} matches {SOURCE.relative_to(REPO)}")
        return
    OUTPUT.write_text(swift, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(REPO)}")


if __name__ == "__main__":
    main()
