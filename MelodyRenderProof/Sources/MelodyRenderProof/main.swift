import Foundation
import MelodyRenderKit
import RecordingAnalysisKit

private struct FixtureManifest: Decodable {
    let recordings: [FixtureRecording]
}

private struct FixtureRecording: Decodable {
    let id: String
    let filename: String
    let permission: String
}

private struct ReviewItem {
    let evidence: RenderEvidence
    let audioURL: URL
    let evidenceURL: URL
}

@main
private enum MelodyRenderProofCLI {
    static func main() throws {
        let arguments = CommandLine.arguments
        guard arguments.count >= 4 else {
            fputs("usage: melody-render-proof <approved-recordings.json> <fixture-directory> <output-directory> [--batch]\n", stderr)
            exit(2)
        }
        let manifestURL = URL(fileURLWithPath: arguments[1])
        let fixtureDirectory = URL(fileURLWithPath: arguments[2], isDirectory: true)
        let outputDirectory = URL(fileURLWithPath: arguments[3], isDirectory: true)
        let batch = arguments.contains("--batch")
        try FileManager.default.createDirectory(at: outputDirectory, withIntermediateDirectories: true)

        let manifest = try JSONDecoder().decode(FixtureManifest.self, from: Data(contentsOf: manifestURL))
        let candidates = try manifest.recordings.map { item in
            let url = fixtureDirectory.appendingPathComponent(item.filename)
            return RecordingCandidate(
                id: item.id,
                filename: item.filename,
                url: url,
                permission: item.permission,
                analysis: try RecordingFileAnalyzer.analyze(url: url)
            )
        }
        let items = try buildListeningPack(candidates: candidates, outputDirectory: outputDirectory)
        try writeIndex(items: items, outputDirectory: outputDirectory)
        if batch {
            print("Generated \(items.count) listening variants in \(outputDirectory.path)")
            return
        }
        review(items)
    }

    private static func buildListeningPack(candidates: [RecordingCandidate], outputDirectory: URL) throws -> [ReviewItem] {
        var items: [ReviewItem] = []
        let encoder = JSONEncoder()
        encoder.outputFormatting = [.prettyPrinted, .sortedKeys, .withoutEscapingSlashes]

        for melody in CuratedMelodyCatalog.all {
            let individual = try MelodyFitPlanner.individualCandidate(for: melody, candidates: candidates)
            for mode in SourceMode.allCases {
                let sourceSet = try MelodyFitPlanner.sourceSet(
                    mode: mode,
                    melody: melody,
                    candidates: candidates,
                    individualID: individual.id
                )
                let stem = "\(melody.id)__\(mode.rawValue)"
                let audioURL = outputDirectory.appendingPathComponent(stem).appendingPathExtension("wav")
                let evidenceURL = outputDirectory.appendingPathComponent(stem).appendingPathExtension("json")
                let evidence = try FartOnlyRenderer.render(melody: melody, sourceSet: sourceSet, outputURL: audioURL)
                try encoder.encode(evidence).write(to: evidenceURL, options: .atomic)
                items.append(ReviewItem(evidence: evidence, audioURL: audioURL, evidenceURL: evidenceURL))
            }
        }
        return items
    }

    private static func writeIndex(items: [ReviewItem], outputDirectory: URL) throws {
        var markdown = """
        # Curated Melody Fit listening pack

        Generated by `deterministic-resample-pingpong-v1` from the approved Fixture Library.
        Every output is fart-only: no vocals, instruments, backing track, synthesizer, or imported performance.

        `choose-individual` selects one Recording, `use-all` makes every approved Recording eligible,
        and `recommend-best-fit` selects up to five pitch-available Recordings using only approved Recording Analysis evidence.

        Melody note plans are direct encodings of compositions that substantially predate 1931. The U.S. Copyright Office states
        that works published in the United States before January 1, 1931 are in the public domain:
        https://copyright.gov/what-is-copyright/

        Listening questions for each row:

        1. Is the melody recognizable without reading its title?
        2. Does it still unmistakably sound fart-only?
        3. Are artifacts acceptable for an MVP proof?
        4. Which source mode should become the implementation baseline?

        | Melody | Source mode | WAV | Evidence |
        | --- | --- | --- | --- |
        """
        for item in items {
            markdown += "\n| \(item.evidence.melody.title) | `\(item.evidence.sourceMode.rawValue)` | [listen](\(item.audioURL.lastPathComponent)) | [inspect](\(item.evidenceURL.lastPathComponent)) |"
        }
        markdown += "\n"
        try markdown.write(to: outputDirectory.appendingPathComponent("README.md"), atomically: true, encoding: .utf8)
    }

    private static func review(_ items: [ReviewItem]) {
        guard !items.isEmpty else { return }
        var index = 0
        var player: Process?
        while true {
            let item = items[index]
            print("\u{001B}[2J\u{001B}[H", terminator: "")
            print("\u{001B}[1mCurated Melody Fit listening proof\u{001B}[0m  \u{001B}[2m\(index + 1)/\(items.count)\u{001B}[0m")
            print("\n\u{001B}[1mMelody\u{001B}[0m        \(item.evidence.melody.title)")
            print("\u{001B}[1mSource mode\u{001B}[0m    \(item.evidence.sourceMode.rawValue)")
            print("\u{001B}[1mSelected IDs\u{001B}[0m   \(item.evidence.fit.selectedRecordingIDs.joined(separator: ", "))")
            print("\u{001B}[1mUsed IDs\u{001B}[0m       \(item.evidence.fit.usedRecordingIDs.joined(separator: ", "))")
            print("\u{001B}[1mPitch-backed\u{001B}[0m   \(item.evidence.fit.pitchedAssignmentCount)/\(item.evidence.fit.noteAssignmentCount) notes")
            print(String(format: "\u{001B}[1mShift evidence\u{001B}[0m mean %.1f, max %.1f semitones", item.evidence.fit.meanAbsoluteSemitoneShift, item.evidence.fit.maximumAbsoluteSemitoneShift))
            print("\u{001B}[1mRepeated notes\u{001B}[0m  \(item.evidence.fit.repeatedOrPaddedNoteCount)")
            if item.evidence.fit.warnings.isEmpty {
                print("\u{001B}[1mWarnings\u{001B}[0m        none")
            } else {
                print("\u{001B}[1mWarnings\u{001B}[0m        \(item.evidence.fit.warnings.joined(separator: " "))")
            }
            print("\n\u{001B}[2m\(item.audioURL.lastPathComponent)\u{001B}[0m")
            print("\n\u{001B}[1m[p]\u{001B}[0m play/stop  \u{001B}[1m[n]\u{001B}[0m next  \u{001B}[1m[b]\u{001B}[0m back  \u{001B}[1m[q]\u{001B}[0m quit")
            guard let command = readLine()?.lowercased().first else { continue }
            switch command {
            case "p":
                if let player, player.isRunning {
                    player.terminate()
                    self.wait(player)
                } else {
                    let process = Process()
                    process.executableURL = URL(fileURLWithPath: "/usr/bin/afplay")
                    process.arguments = [item.audioURL.path]
                    try? process.run()
                    player = process
                }
            case "n":
                stop(&player)
                index = (index + 1) % items.count
            case "b":
                stop(&player)
                index = (index - 1 + items.count) % items.count
            case "q":
                stop(&player)
                return
            default:
                continue
            }
        }
    }

    private static func stop(_ player: inout Process?) {
        if let player, player.isRunning {
            player.terminate()
            wait(player)
        }
        player = nil
    }

    private static func wait(_ player: Process) {
        player.waitUntilExit()
    }
}
